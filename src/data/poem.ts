export interface Chapter {
  numeral: string;
  title: string;
  mood: 'ash' | 'ember' | 'dawn' | 'struggle' | 'glow' | 'light';
  lines: string[];
}

export interface StanzaItem {
  numeral: string;
  subtitle?: string;
  mood: 'autumn' | 'corridor' | 'dawn' | 'spark' | 'ash' | 'ember' | 'glow' | 'light' | 'struggle';
  lines: string[];
}

export interface PoemMeaning {
  title: string;
  subtitle: string;
  paragraphs: string[];
}

export interface PoemItem {
  id: string;
  title: string;
  subtitle: string;
  category: string;
  year?: string;
  readingTime: string;
  previewQuote: string;
  description: string;
  tags: string[];
  gradient: string;
  accentColor: string;
  borderGlow: string;
  stanzas: StanzaItem[];
  meaning?: PoemMeaning;
  finale?: {
    text: string;
    subtext: string;
  };
}

